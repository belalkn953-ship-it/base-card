drop policy if exists profiles_self_or_admin on public.profiles;
create policy profiles_self_or_admin on public.profiles for select using (id=auth.uid() or public.is_admin());
drop policy if exists profiles_self_update on public.profiles;
create policy profiles_self_update on public.profiles for update using (id=auth.uid());

drop policy if exists games_public_read on public.games;
create policy games_public_read on public.games for select using (visible=true or public.is_admin());
drop policy if exists games_admin_insert on public.games;
create policy games_admin_insert on public.games for insert with check (public.is_admin());
drop policy if exists games_admin_update on public.games;
create policy games_admin_update on public.games for update using (public.is_admin());
drop policy if exists games_admin_delete on public.games;
create policy games_admin_delete on public.games for delete using (public.is_admin());

drop policy if exists packages_public_read on public.packages;
create policy packages_public_read on public.packages for select using ((visible=true and exists(select 1 from public.games g where g.id=game_id and g.visible=true)) or public.is_admin());
drop policy if exists packages_admin_insert on public.packages;
create policy packages_admin_insert on public.packages for insert with check (public.is_admin());
drop policy if exists packages_admin_update on public.packages;
create policy packages_admin_update on public.packages for update using (public.is_admin());
drop policy if exists packages_admin_delete on public.packages;
create policy packages_admin_delete on public.packages for delete using (public.is_admin());

drop policy if exists settings_public_read on public.settings;
create policy settings_public_read on public.settings for select using (true);
drop policy if exists settings_admin_write on public.settings;
create policy settings_admin_write on public.settings for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists orders_insert_own on public.orders;
create policy orders_insert_own on public.orders for insert with check (auth.uid()=user_id);
drop policy if exists orders_read_own_or_admin on public.orders;
create policy orders_read_own_or_admin on public.orders for select using (auth.uid()=user_id or public.is_admin());
drop policy if exists orders_admin_update on public.orders;
create policy orders_admin_update on public.orders for update using (public.is_admin());

drop policy if exists messages_insert_any on public.messages;
create policy messages_insert_any on public.messages for insert with check (auth.uid()=user_id or user_id is null);
drop policy if exists messages_admin_read on public.messages;
create policy messages_admin_read on public.messages for select using (public.is_admin());

