create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '',
  name text not null default '',
  avatar text not null default '',
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id,email,name,avatar)
  values (new.id, coalesce(new.email,''), coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', coalesce(new.email,'')), coalesce(new.raw_user_meta_data->>'avatar_url',''))
  on conflict (id) do update set email=excluded.email, name=excluded.name, avatar=excluded.avatar, updated_at=now();
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique not null,
  icon text not null default '🎮',
  description text not null default '',
  visible boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.packages (
  id bigint generated by default as identity primary key,
  game_id bigint not null references public.games(id) on delete cascade,
  name text not null,
  price text not null,
  note text not null default '',
  visible boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique(game_id,name)
);
create table if not exists public.settings (
  key text primary key,
  value text not null default ''
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number text unique not null,
  user_id uuid not null references public.profiles(id) on delete restrict,
  game_id bigint not null references public.games(id),
  package_id bigint not null references public.packages(id),
  player_id text not null,
  customer_name text not null,
  payment_number text not null,
  receipt_path text,
  status text not null default 'pending' check(status in ('pending','processing','completed','rejected')),
  admin_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  name text not null,
  contact text not null,
  message text not null,
  created_at timestamptz not null default now()
);

